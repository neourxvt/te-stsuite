#!/usr/bin/env python3
"""Generate C arrays that preserve the benchmark fixture bytes exactly."""

from pathlib import Path
import sys


SYMBOLS = {
    "unicode_symbols.txt": "te_stsuite_unicode_symbols",
    "medium_cells.vim": "te_stsuite_medium_cells",
    "sync_medium_cells.vim": "te_stsuite_sync_medium_cells",
}


def format_bytes(payload):
    """Format fixture bytes as portable unsigned C integer literals."""
    for start in range(0, len(payload), 12):
        chunk = payload[start : start + 12]
        yield "    " + ", ".join(f"0x{value:02x}" for value in chunk) + ","


def main():
    if len(sys.argv) != len(SYMBOLS) + 2:
        raise SystemExit("expected three fixture paths followed by an output path")

    fixture_paths = [Path(path) for path in sys.argv[1:-1]]
    output_path = Path(sys.argv[-1])
    generated = [
        "#include \"te-stsuite.h\"",
        "",
        "/* Generated from the benchmark fixtures; do not edit this file. */",
        "",
    ]

    seen = set()
    for fixture_path in fixture_paths:
        symbol = SYMBOLS.get(fixture_path.name)
        if symbol is None or symbol in seen:
            raise SystemExit(f"unexpected or duplicate fixture: {fixture_path}")
        seen.add(symbol)

        payload = fixture_path.read_bytes()
        array_size = max(1, len(payload))
        generated.append(f"const unsigned char {symbol}[{array_size}] = {{")
        if payload:
            generated.extend(format_bytes(payload))
        else:
            generated.append("    0x00,")
        generated.extend(
            [
                "};",
                f"const size_t {symbol}_length = {len(payload)};",
                "",
            ]
        )

    if seen != set(SYMBOLS.values()):
        raise SystemExit("all three benchmark fixtures must be provided")

    output_path.write_text("\n".join(generated) + "\n", encoding="ascii")


if __name__ == "__main__":
    main()
